#!/bin/bash
# Network-namespace lab for TCP MSS/MTU behaviour of DIRD-configured containers.
# See https://github.com/newsnowlabs/docker-ingress-routing-daemon/issues/43
#
# Topology (no Docker required; run as root on a disposable host):
#
#  client  203.0.113.10                       MTU $CLIENT_MTU (default 1500)
#     |
#  lb      203.0.113.1 | 10.0.0.2 (ingress)   ingress_sbox analogue: DNAT without SNAT,
#     |                                       sets TOS 2 (DIRD step 1) towards the ingress subnet
#  srv     eth0 10.0.0.5  (ingress)           MTU $OVERLAY_MTU (default 1450)
#          eth1 172.18.0.3 (default route)    MTU 1500 (docker_gwbridge analogue)
#     |
#  gw      172.18.0.1
#
# DIRD's own route_ingress() function is extracted from the script under test and run against
# the 'srv' namespace, with 'docker inspect' stubbed to return the PID of a process in that namespace.
#
# The client connects, reports its TCP_MAXSEG (derived from the MSS advertised in the SYN-ACK),
# then sends 3000 bytes (forcing full-sized segments); the server reads them and replies with
# 4000 bytes of padding plus the byte count, the accepted socket's fwmark and its TCP_MAXSEG.
#
# Usage: lab.sh <path-to-dird-script> [blackhole]
#
#   blackhole       - drop ICMP 'fragmentation needed' generated by lb, simulating a PMTUD black hole
#   OVERLAY_MTU=n   - MTU of the ingress link (lb <-> srv)
#   CLIENT_MTU=n    - MTU of the client's interface (the lb side remains 1500, as for an internet path)
#   LBRULE='...'    - optional extra iptables rule (arguments) to install in lb, e.g. a TCPMSS rule
#
# Output lines are prefixed 'RESULT' for machine parsing:
#   RESULT client_mss=<n> received=<bytes server received> mark=<accepted socket mark> server_mss=<n> reply=<bytes client received>

DIRD="$1"; BLACKHOLE="${2:-}"
OVERLAY_MTU="${OVERLAY_MTU:-1450}"
CLIENT_MTU="${CLIENT_MTU:-1500}"

cleanup() {
  for n in client lb srv gw; do ip netns pids $n 2>/dev/null | xargs -r kill 2>/dev/null; ip netns del $n 2>/dev/null; done
}
cleanup
trap cleanup EXIT
for n in client lb srv gw; do ip netns add $n; ip -n $n link set lo up; done

ip link add c0 netns client type veth peer name l0 netns lb
ip link add l1 netns lb type veth peer name eth0 netns srv
ip link add eth1 netns srv type veth peer name g0 netns gw

ip -n client addr add 203.0.113.10/24 dev c0; ip -n client link set c0 mtu $CLIENT_MTU up
ip -n client route add default via 203.0.113.1

ip -n lb addr add 203.0.113.1/24 dev l0; ip -n lb link set l0 up
ip -n lb addr add 10.0.0.2/24 dev l1; ip -n lb link set l1 mtu $OVERLAY_MTU up
ip netns exec lb sysctl -qw net.ipv4.ip_forward=1
ip netns exec lb iptables -t nat -A PREROUTING -d 203.0.113.1 -p tcp --dport 80 -j DNAT --to-destination 10.0.0.5:80
ip netns exec lb iptables -t mangle -A POSTROUTING -d 10.0.0.0/24 -j TOS --set-tos 2/0xff
[ -n "${LBRULE:-}" ] && ip netns exec lb iptables $LBRULE
[ "$BLACKHOLE" = blackhole ] && ip netns exec lb iptables -A OUTPUT -p icmp --icmp-type fragmentation-needed -j DROP

ip -n srv addr add 10.0.0.5/24 dev eth0; ip -n srv link set eth0 mtu $OVERLAY_MTU up
ip -n srv addr add 172.18.0.3/16 dev eth1; ip -n srv link set eth1 up
ip -n srv route add default via 172.18.0.1
ip -n gw addr add 172.18.0.1/16 dev g0; ip -n gw link set g0 up

# Long-lived process in the srv namespace, standing in for the container's PID
ip netns exec srv sleep 1000 & SRVPID=$!
sleep 0.2

# Run DIRD's real route_ingress() against the 'container'
docker() { [ "$1" = inspect ] && echo $SRVPID; }
INGRESS_SUBNET=10.0.0.0/24
INGRESS_NODE_GATEWAY_IPS=(10.0.0.2)
IPTABLES_OPTS=()
SERVICES=()
JOURNAL_STREAM=1
source <(sed -n '/^log() {/,/^}/p;/^route_ingress() {/,/^}/p' "$DIRD")
route_ingress fakeid fakeservice | sed 's/^/  [dird] /'

ip netns exec srv python3 -u -c '
import socket
s=socket.socket(); s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
s.bind(("0.0.0.0",80)); s.listen(16)
while True:
    c,a=s.accept()
    mark=c.getsockopt(socket.SOL_SOCKET, 36)  # SO_MARK
    n=0
    c.settimeout(5)
    try:
        while n<3000:
            d=c.recv(65536)
            if not d: break
            n+=len(d)
    except Exception: pass
    try: c.sendall(b"y"*4000 + b"received=%d mark=%d server_mss=%d" % (n, mark, c.getsockopt(socket.IPPROTO_TCP, socket.TCP_MAXSEG)))
    except Exception: pass
    c.close()
' >/dev/null 2>&1 &
sleep 0.5

ip netns exec client python3 -c '
import socket
c=socket.create_connection(("203.0.113.1",80),timeout=8)
mss=c.getsockopt(socket.IPPROTO_TCP, socket.TCP_MAXSEG)
buf=b""
try:
    c.sendall(b"x"*3000)
    while True:
        d=c.recv(65536)
        if not d: break
        buf+=d
except Exception: pass
info=buf[4000:].decode() or "received=? mark=? server_mss=?"
print("RESULT client_mss=%d %s reply=%d" % (mss, info, len(buf)))
'
echo "  srv route exceptions: $(ip -n srv route show cache | tr '\n' ' ')"
